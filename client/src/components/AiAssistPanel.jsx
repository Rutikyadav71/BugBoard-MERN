import { useState } from 'react';
import { AlertCircle, Check, Info, Lightbulb, Loader2, RefreshCw, Sparkles, Wand2, X } from 'lucide-react';
import { aiApi } from '../api/ai.js';
import { getErrorMessage } from '../api/client.js';
import useAsync from '../hooks/useAsync.js';
import ErrorMessage from './ErrorMessage.jsx';
import { CATEGORIES, PRIORITIES, SEVERITIES } from '../utils/constants.js';

const toOptions = (list) => list.map((v) => ({ value: v, label: v }));

function MetaLine({ meta }) {
  return (
    <p className="mt-2 flex flex-wrap items-center gap-x-2 gap-y-1 text-xs text-slate-500">
      <Info size={12} className="shrink-0" />
      <span>{meta.notice}</span>
      {meta.demo
        ? <span className="rounded-full bg-amber-100 px-2 py-0.5 font-medium text-amber-800">Demo provider: not a real model</span>
        : <span className="text-slate-400">Generated by {meta.model}</span>}
    </p>
  );
}

function Warnings({ items }) {
  if (!items?.length) return null;
  return (
    <ul className="mt-3 space-y-1 rounded-lg border border-amber-200 bg-amber-50 p-3 text-sm text-amber-800" aria-label="Warnings">
      {items.map((w) => <li key={w} className="flex gap-2"><AlertCircle size={14} className="mt-0.5 shrink-0" /><span>{w}</span></li>)}
    </ul>
  );
}

// AI assistance for the issue form. Everything it returns is a SUGGESTION: the form is only changed when the
// user presses Accept / Use. `getValues` and `setValue` come from the form's react-hook-form instance.
export default function AiAssistPanel({ projectId, getValues, setValue, isAdmin = false, assignable = [] }) {
  const status = useAsync(() => aiApi.status(), []);
  const [context, setContext] = useState('');
  const [busy, setBusy] = useState(null); // 'triage' | 'improve' | null
  const [error, setError] = useState('');
  const [triage, setTriage] = useState(null); // { result, draft, decisions, detailsAdded }
  const [improve, setImprove] = useState(null); // { result, text, title, useTitle, applied }

  const available = status.data?.available === true;
  const unavailableReason = status.error ? 'Could not check whether AI is available.' : status.data?.reason;

  function readReport() {
    const title = (getValues('title') || '').trim();
    if (title.length < 3) throw new Error('Enter a title (at least 3 characters) first.');
    const project = projectId || getValues('project');
    if (!project) throw new Error('Choose a project first.');
    return { project, title, description: (getValues('description') || '').trim(), context: context.trim() };
  }

  async function runTriage() {
    setError('');
    let body;
    try { body = readReport(); } catch (e) { setError(e.message); return; }
    setBusy('triage');
    try {
      const result = await aiApi.triage(body);
      const s = result.suggestions;
      setTriage({
        result, decisions: {}, detailsAdded: false,
        draft: { category: s.category || '', severity: s.severity || '', priority: s.priority || '', component: s.component || '', assignee: s.suggestedAssignee?.id || '' },
      });
    } catch (err) { setError(getErrorMessage(err, 'AI triage failed')); } finally { setBusy(null); }
  }

  async function runImprove() {
    setError('');
    let body;
    try { body = readReport(); } catch (e) { setError(e.message); return; }
    setBusy('improve');
    try {
      const result = await aiApi.improve(body);
      setImprove({ result, text: result.improved.description, title: result.improved.title, useTitle: false, applied: false });
    } catch (err) { setError(getErrorMessage(err, 'AI improvement failed')); } finally { setBusy(null); }
  }

  const decide = (key, value) => setTriage((t) => ({ ...t, decisions: { ...t.decisions, [key]: value } }));
  const edit = (key, value) => setTriage((t) => ({ ...t, draft: { ...t.draft, [key]: value } }));
  const accept = (row) => { setValue(row.field, triage.draft[row.key], { shouldDirty: true }); decide(row.key, 'accepted'); };

  function triageRows() {
    const s = triage.result.suggestions;
    const rows = [];
    if (s.category) rows.push({ key: 'category', field: 'category', label: 'Category', options: toOptions(CATEGORIES) });
    if (s.severity) rows.push({ key: 'severity', field: 'severity', label: 'Severity', options: toOptions(SEVERITIES), reason: s.reasoning.severity });
    if (s.priority) rows.push({ key: 'priority', field: 'priority', label: 'Priority', options: toOptions(PRIORITIES), reason: s.reasoning.priority });
    if (s.component) rows.push({ key: 'component', field: 'component', label: 'Component' });
    if (isAdmin && s.suggestedAssignee) {
      rows.push({
        key: 'assignee', field: 'assignee', label: 'Assignee', options: assignable.map((u) => ({ value: u._id, label: u.name })),
        reason: s.reasoning.assignee, note: `${s.suggestedAssignee.activeIssues} active issue${s.suggestedAssignee.activeIssues === 1 ? '' : 's'} right now`,
      });
    }
    return rows;
  }

  function addDetails() {
    const s = triage.result.suggestions;
    const parts = [];
    if (s.stepsToReproduce.length) parts.push(`Steps to reproduce:\n${s.stepsToReproduce.map((x, i) => `${i + 1}. ${x}`).join('\n')}`);
    if (s.expectedBehavior) parts.push(`Expected behavior:\n${s.expectedBehavior}`);
    if (s.actualBehavior) parts.push(`Actual behavior:\n${s.actualBehavior}`);
    const current = (getValues('description') || '').trim();
    setValue('description', [current, ...parts].filter(Boolean).join('\n\n'), { shouldDirty: true });
    setTriage((t) => ({ ...t, detailsAdded: true }));
  }

  function useImproved() {
    setValue('description', improve.text, { shouldDirty: true });
    if (improve.useTitle && improve.title.trim().length >= 3) setValue('title', improve.title.trim().slice(0, 200), { shouldDirty: true });
    setImprove((i) => ({ ...i, applied: true }));
  }

  const checking = status.loading && !status.data;
  const disabled = !available || busy !== null;

  return (
    <section className="rounded-xl border border-violet-200 bg-violet-50/40 p-4" aria-labelledby="ai-heading">
      <div className="flex flex-wrap items-center justify-between gap-2">
        <h2 id="ai-heading" className="flex items-center gap-2 text-sm font-semibold text-violet-900"><Sparkles size={16} /> AI assistant <span className="rounded-full bg-violet-100 px-2 py-0.5 text-xs font-medium text-violet-700">suggestions only</span></h2>
        <div className="flex flex-wrap gap-2">
          <button type="button" className="btn-secondary py-1.5" onClick={runTriage} disabled={disabled}>
            {busy === 'triage' ? <Loader2 size={14} className="animate-spin" /> : <Lightbulb size={14} />} {busy === 'triage' ? 'Analysing…' : 'Suggest triage'}
          </button>
          <button type="button" className="btn-secondary py-1.5" onClick={runImprove} disabled={disabled}>
            {busy === 'improve' ? <Loader2 size={14} className="animate-spin" /> : <Wand2 size={14} />} {busy === 'improve' ? 'Improving…' : 'Improve description'}
          </button>
        </div>
      </div>

      <div aria-live="polite">
        {checking && <p className="mt-2 text-sm text-slate-500">Checking AI availability…</p>}
        {!checking && !available && <p className="mt-2 text-sm text-slate-600">AI suggestions are unavailable: {unavailableReason} You can still fill in the form yourself.</p>}
        {available && status.data.dataNotice && <p className="mt-2 text-xs text-slate-500">{status.data.dataNotice}</p>}
      </div>

      {available && (
        <div className="mt-3">
          <label htmlFor="ai-context" className="label text-xs">Extra context for the AI (optional)</label>
          <textarea id="ai-context" rows={2} maxLength={1000} className="input" placeholder="Environment, what you already tried…" value={context} onChange={(e) => setContext(e.target.value)} />
        </div>
      )}

      <ErrorMessage message={error} className="mt-3" />

      {triage && (
        <div className="mt-4 rounded-lg border border-slate-200 bg-white p-3" aria-label="Triage suggestions">
          <h3 className="text-sm font-semibold text-slate-800">Triage suggestions</h3>
          <p className="text-xs text-slate-500">Edit any value, then accept or dismiss each one. Nothing is applied until you accept it.</p>
          <ul className="mt-2 divide-y divide-slate-100">
            {triageRows().map((row) => {
              const decision = triage.decisions[row.key];
              return (
                <li key={row.key} className={`py-2 ${decision === 'rejected' ? 'opacity-50' : ''}`}>
                  <div className="flex flex-wrap items-center gap-2">
                    <label htmlFor={`ai-${row.key}`} className="w-20 shrink-0 text-sm font-medium text-slate-700">{row.label}</label>
                    {row.options ? (
                      <select id={`ai-${row.key}`} className="input w-auto min-w-0 flex-1 py-1 sm:max-w-[14rem]" value={triage.draft[row.key]} disabled={Boolean(decision)} onChange={(e) => edit(row.key, e.target.value)}>
                        {row.options.map((o) => <option key={o.value} value={o.value}>{o.label}</option>)}
                      </select>
                    ) : (
                      <input id={`ai-${row.key}`} className="input w-auto min-w-0 flex-1 py-1 sm:max-w-[14rem]" value={triage.draft[row.key]} maxLength={80} disabled={Boolean(decision)} onChange={(e) => edit(row.key, e.target.value)} />
                    )}
                    {!decision && (
                      <span className="flex gap-1">
                        <button type="button" className="btn-primary px-2 py-1" onClick={() => accept(row)} aria-label={`Accept ${row.label.toLowerCase()} suggestion`}><Check size={14} /> Accept</button>
                        <button type="button" className="btn-secondary px-2 py-1" onClick={() => decide(row.key, 'rejected')} aria-label={`Dismiss ${row.label.toLowerCase()} suggestion`}><X size={14} /></button>
                      </span>
                    )}
                    {decision === 'accepted' && <span className="inline-flex items-center gap-1 text-xs font-medium text-emerald-700"><Check size={14} /> Applied to the form</span>}
                    {decision === 'rejected' && <span className="text-xs text-slate-500">Dismissed</span>}
                  </div>
                  {(row.reason || row.note) && <p className="ml-0 mt-1 text-xs text-slate-500 sm:ml-[5.5rem]">{[row.reason, row.note].filter(Boolean).join(' · ')}</p>}
                </li>
              );
            })}
          </ul>

          {(triage.result.suggestions.stepsToReproduce.length > 0 || triage.result.suggestions.expectedBehavior || triage.result.suggestions.actualBehavior) && (
            <div className="mt-2 rounded-lg bg-slate-50 p-3 text-sm text-slate-700">
              <p className="font-medium">Details found in your text</p>
              {triage.result.suggestions.stepsToReproduce.length > 0 && <ol className="ml-5 mt-1 list-decimal text-xs">{triage.result.suggestions.stepsToReproduce.map((x) => <li key={x}>{x}</li>)}</ol>}
              {triage.result.suggestions.expectedBehavior && <p className="mt-1 text-xs"><span className="font-medium">Expected:</span> {triage.result.suggestions.expectedBehavior}</p>}
              {triage.result.suggestions.actualBehavior && <p className="mt-1 text-xs"><span className="font-medium">Actual:</span> {triage.result.suggestions.actualBehavior}</p>}
              <button type="button" className="btn-secondary mt-2 px-2 py-1" onClick={addDetails} disabled={triage.detailsAdded}>{triage.detailsAdded ? 'Added to description' : 'Add to description'}</button>
            </div>
          )}

          {triage.result.suggestions.missingInformation.length > 0 && (
            <div className="mt-2 text-sm text-slate-700">
              <p className="font-medium">Questions to answer before submitting</p>
              <ul className="ml-5 mt-1 list-disc text-xs">{triage.result.suggestions.missingInformation.map((q) => <li key={q}>{q}</li>)}</ul>
            </div>
          )}
          <Warnings items={triage.result.warnings} />
          <MetaLine meta={triage.result.meta} />
          <button type="button" className="mt-2 text-xs font-medium text-slate-500 hover:text-slate-800" onClick={() => setTriage(null)}>Close suggestions</button>
        </div>
      )}

      {improve && (
        <div className="mt-4 rounded-lg border border-slate-200 bg-white p-3" aria-label="Improved description">
          <h3 className="text-sm font-semibold text-slate-800">Improved description</h3>
          <p className="text-xs text-slate-500">Compare, edit the improved text if you like, then choose whether to use it. Your description is not changed until you do.</p>
          <div className="mt-2 grid grid-cols-1 gap-3 md:grid-cols-2">
            <div>
              <label htmlFor="ai-original" className="label text-xs">Your original</label>
              <textarea id="ai-original" rows={8} readOnly className="input bg-slate-50 text-slate-600" value={improve.result.original.description || '(no description entered)'} />
            </div>
            <div>
              <label htmlFor="ai-improved" className="label text-xs">Improved (editable)</label>
              <textarea id="ai-improved" rows={8} maxLength={5000} className="input" value={improve.text} onChange={(e) => setImprove((i) => ({ ...i, text: e.target.value, applied: false }))} />
            </div>
          </div>
          <label className="mt-2 flex items-start gap-2 text-sm text-slate-700">
            <input type="checkbox" className="mt-1 h-4 w-4 rounded border-slate-300 text-brand-600" checked={improve.useTitle} onChange={(e) => setImprove((i) => ({ ...i, useTitle: e.target.checked }))} />
            <span>Also replace the title with a suggested one</span>
          </label>
          {improve.useTitle && <input aria-label="Suggested title" className="input mt-1" maxLength={200} value={improve.title} onChange={(e) => setImprove((i) => ({ ...i, title: e.target.value }))} />}
          {improve.result.improved.missingDetails.length > 0 && (
            <div className="mt-2 text-sm text-slate-700">
              <p className="font-medium">Still needed from you</p>
              <ul className="ml-5 mt-1 list-disc text-xs">{improve.result.improved.missingDetails.map((m) => <li key={m}>{m}</li>)}</ul>
            </div>
          )}
          <Warnings items={improve.result.warnings} />
          <div className="mt-3 flex flex-wrap items-center gap-2">
            <button type="button" className="btn-primary px-3 py-1.5" onClick={useImproved} disabled={!improve.text.trim()}><Check size={14} /> Use improved description</button>
            <button type="button" className="btn-secondary px-3 py-1.5" onClick={runImprove} disabled={disabled}><RefreshCw size={14} /> Regenerate</button>
            <button type="button" className="btn-secondary px-3 py-1.5" onClick={() => setImprove(null)}>Discard</button>
            {improve.applied && <span role="status" className="text-xs font-medium text-emerald-700">Description replaced in the form above.</span>}
          </div>
          <MetaLine meta={improve.result.meta} />
        </div>
      )}
    </section>
  );
}
